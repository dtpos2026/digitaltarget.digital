/** Every theme the picker can apply: the thirteen Modern ones, then the DT Retail eight. */
export const ALL_THEMES: UiTheme[] = [...UI_THEMES, ...RETAIL_THEMES];

export const DEFAULT_THEME_ID = 'ember';

/** The DT Retail POS v1.8 look (PIN sign-in page, stacked clock, category dots). */
export const ESPRESSO_THEME_ID = 'dtr-espresso';

// Themes designed in Settings → Custom (or imported from a theme file). Registered by
// lib/customTheme.ts at start-up; the built-in lists above are never changed.
let customThemes: UiTheme[] = [];

export function registerCustomThemes(list: UiTheme[]): void {
  customThemes = list.filter(t => t.custom && t.id !== DEFAULT_THEME_ID && !ALL_THEMES.some(b => b.id === t.id));
}

export function getRegisteredCustomThemes(): UiTheme[] {
  return customThemes;
}

export function findTheme(id: string | null | undefined): UiTheme {
  return ALL_THEMES.find(t => t.id === id) || customThemes.find(t => t.id === id) || UI_THEMES[0];
}

export const isThemeId = (id: unknown): id is string =>
  typeof id === 'string' && (ALL_THEMES.some(t => t.id === id) || customThemes.some(t => t.id === id));

/** True for a DT Retail theme (the look with the gradient sidebar, hero banner and motion), built in or custom. */
export const isRetailTheme = (id: unknown): boolean =>
  typeof id === 'string' && (RETAIL_THEMES.some(t => t.id === id) || customThemes.some(t => t.id === id && t.family === 'retail'));

/** True for a theme made in Settings → Custom. */
export const isCustomTheme = (id: unknown): boolean => typeof id === 'string' && customThemes.some(t => t.id === id);
